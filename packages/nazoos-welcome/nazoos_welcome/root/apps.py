"""Optional apps: Flatpaks from Flathub and RPMs (catalog.APPS)."""

import configparser
import io
import re
from pathlib import Path

from nazoos_common import helper, proc
from nazoos_common.files import write_atomic
from nazoos_common.helper import FLATPAK, Fail, arg, say
from nazoos_common.kernel import running_nazoos
from nazoos_common.zypper import ZYPPER, ZYPPER_IN

from .. import catalog, hw, system
from .base import flathub_ensure


def flatpak_branches():
    listing = helper.output(FLATPAK + ["remote-ls", "flathub",
                                "--columns=application,branch"])
    branches = {}
    for line in listing.splitlines():
        parts = line.split("\t")
        if len(parts) == 2:
            branches.setdefault(parts[0], set()).add(parts[1])
    return branches


def runtime_branch(app_ref):
    """Branch of the runtime an installed app uses, e.g. "25.08"."""
    runtime = helper.output(FLATPAK + ["info", "--show-runtime", app_ref]).strip()
    return runtime.rsplit("/", 1)[-1] if runtime.count("/") == 2 else ""


def pick_branch(found, wanted):
    """WANTED if Flathub has it, else the newest of FOUND."""
    def key(b):
        return [int(x) if x.isdigit() else -1 for x in b.split(".")]

    return wanted if wanted in found else max(found, key=key)


def _install_rpm(app):
    helper.run(ZYPPER_IN + app["refs"])
    for unit in app.get("units", []):
        helper.run(["systemctl", "enable", "--now", unit])
    firewall_trust(app.get("trusted", []), True)
    if app.get("setup"):
        SETUP[app["setup"]]()


def _install_flatpak(app):
    flathub_ensure()
    # Extensions like Vulkan layers exist once per runtime version and
    # cannot be installed without a branch. Install the app first, then
    # pick the branch of the runtime it uses (newest as fallback).
    branches = flatpak_branches()
    single = [r for r in app["refs"] if len(branches.get(r, ())) <= 1]
    multi = [r for r in app["refs"] if len(branches.get(r, ())) > 1]
    helper.run(FLATPAK + ["install", "--noninteractive", "-y", "flathub"] + single)
    if multi:
        wanted = runtime_branch(app["refs"][0])
        refs = [f"{ref}//{pick_branch(branches[ref], wanted)}"
                for ref in multi]
        helper.run(FLATPAK + ["install", "--noninteractive", "-y", "flathub"] + refs)


def app_install(args):
    app = catalog.by_id(catalog.APPS, arg(args, 0))
    if app is None:
        raise Fail("unknown app")
    if app.get("kernel") == "nazoos" and not running_nazoos():
        raise Fail("{app} needs the NazoOS kernel (Kernel page)",
                   app=app["name"])
    if app["kind"] == "flatpak":
        _install_flatpak(app)
    else:
        _install_rpm(app)


def app_remove(args):
    app = catalog.by_id(catalog.APPS, arg(args, 0))
    if app is None:
        raise Fail("unknown app")
    if app["kind"] == "flatpak":
        # One by one: removing the app also removes its own extensions
        for ref in app["refs"]:
            installed = helper.output(FLATPAK + ["list",
                                          "--columns=application"]).split()
            if ref in installed:
                helper.run(FLATPAK + ["uninstall", "--noninteractive", "-y", ref])
    else:
        for unit in app.get("units", []):
            helper.run(["systemctl", "disable", "--now", unit], check=False)
        helper.run(ZYPPER + ["remove", "--clean-deps"] + app["refs"])
        firewall_trust(app.get("trusted", []), False)


def waydroid_config():
    """Android properties for Waydroid: the time zone of the system
    (Android runs in UTC otherwise) and, in a VM, software rendering
    (system.WAYDROID_SOFTWARE). Written before Waydroid's first start:
    its init loads an existing config and keeps [properties]. Already set
    up: rebuild Android's properties now, they are only generated by init
    and upgrade."""
    wanted = {}
    tz = helper.output(["timedatectl", "show", "--property=Timezone",
                 "--value"]).strip()
    if re.fullmatch(r"[A-Za-z0-9_+-]+(/[A-Za-z0-9_+-]+)*", tz):
        wanted["persist.sys.timezone"] = tz
    if hw.in_vm():
        wanted.update(system.WAYDROID_SOFTWARE)
    path = Path(system.WAYDROID_CONFIG)
    cfg = configparser.ConfigParser(interpolation=None)
    cfg.read(path)
    if "properties" not in cfg:
        cfg["properties"] = {}
    props = cfg["properties"]
    if all(props.get(k) == v for k, v in wanted.items()):
        return
    if hw.in_vm():
        say("Virtual machine: Waydroid uses software rendering")
    props.update(wanted)
    # 0755 like Waydroid's own: the GUI reads the config as the user
    path.parent.mkdir(mode=0o755, parents=True, exist_ok=True)
    buf = io.StringIO()
    cfg.write(buf)
    write_atomic(path, buf.getvalue())
    if Path(system.WAYDROID_ROOTFS).is_dir():
        helper.run(["waydroid", "upgrade", "--offline"])


# Steps after an RPM install, by the "setup" key of catalog.APPS
SETUP = {"waydroid": waydroid_config}


def firewall_trust(ifaces, add):
    """Put network interfaces of an app into firewalld's trusted zone."""
    if not ifaces or proc.rc(
            ["systemctl", "is-active", "--quiet", "firewalld"]) != 0:
        return
    op = "--add" if add else "--remove"
    for iface in ifaces:
        helper.run(["firewall-cmd", "--permanent", "--zone=trusted",
             f"{op}-interface={iface}"], check=False)
    if add:
        # Forwarding inside the zone: Android reaches the internet via the
        # host. Not taken back on removal: other interfaces may need it
        helper.run(["firewall-cmd", "--permanent", "--zone=trusted", "--add-forward"],
            check=False)
    helper.run(["firewall-cmd", "--reload"], check=False)
